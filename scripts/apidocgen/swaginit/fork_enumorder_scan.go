// enumArrayNames are the parallel arrays of an enum schema that must move
// together.
var enumArrayNames = []string{"enum", "x-enum-varnames", "x-enum-descriptions"}

// varnamesKey is the schema member that anchors the permutation.
const varnamesKey = "x-enum-varnames"

// canonicalizeEnumArrays rewrites the enum arrays of every definition whose
// constants swag collected from a fork_*.go file into a deterministic
// order. It edits the JSON bytes of a swag output file in place: the spec
// objects behind the two output files (swagger.json and the docTemplate in
// docs.go) are shared per run, but neither swag's parse step nor its
// writers expose a hook between parse and serialization, so the fix runs on
// the generated bytes instead.
//
// Every element's exact bytes survive, the rewriter only moves whole
// lines, so number spelling, escaping and indentation all survive. An enum
// is only touched when one of its constants was declared in a fork_*.go
// file; every upstream only enum keeps the order swag produced, which for a
// single file is that file's declaration order.
func canonicalizeEnumArrays(data []byte, sources *sourceMap) ([]byte, error) {
	body, err := specBody(data)
	if err != nil {
		return nil, err
	}
	rootStart, rootEnd, err := objectBounds(body, 0)
	if err != nil {
		return nil, err
	}
	defValStart := findMemberValue(body, rootStart+1, rootEnd, "definitions")
	if defValStart < 0 {
		return data, nil
	}
	defObjStart, defObjEnd, err := objectBounds(body, defValStart)
	if err != nil {
		return nil, err
	}
	edits, err := planDefinitionEdits(body, defObjStart, defObjEnd, sources)
	if err != nil {
		return nil, err
	}
	if len(edits) == 0 {
		return data, nil
	}
	// Every edit is an in-place permutation of one multiline array, so
	// the new bytes land at exactly the original offsets in both output
	// files. swagger.json is the whole file; for docs.go the body is the
	// docTemplate raw string, whose bytes are the file's bytes.
	if bodyEqualsData(body, data) || sameSlice(body, data) {
		return spliceEdits(body, edits), nil
	}
	// docs.go: the extracted body starts at docTemplateBounds(data).start
	// inside the file, so the edited regions are copied back shifted by
	// that offset. Copy from the spliced body, not the raw one.
	spliced := spliceEdits(body, edits)
	out := make([]byte, len(data))
	copy(out, data)
	bodyStart := bytes.Index(data, []byte(docTemplateOpen))
	if bodyStart < 0 {
		// specBody already validated the opener.
		return nil, xerrors.New("docs.go: docTemplate start not found")
	}
	bodyStart += len(docTemplateOpen) - 1
	for _, e := range edits {
		copy(out[e.start+bodyStart:e.end+bodyStart], spliced[e.start:e.end])
	}
	return out, nil
}

// sameSlice reports whether body and data hold equal bytes, which is true
// for docs.go because the extracted template is a sub-slice of the file.
func sameSlice(body, data []byte) bool {
	return len(body) == len(data) && bytes.Equal(body, data)
}

// bodyEqualsData reports whether the extracted body is the original data
// slice itself, which is true for swagger.json.
func bodyEqualsData(body, data []byte) bool {
	return len(body) == len(data) && &body[0] == &data[0]
}

// sourceInfo records where one constant was declared and in what scan
// order the file was seen, so fork constants can be ordered without
// depending on swag's random collection order.
type sourceInfo struct {
	file string
	rank int
}

// sourceMap maps a package-qualified constant name to its declaration.
// Keys look like codersdk.ExperimentForkChatTodos.
type sourceMap map[string]sourceInfo

// scanSources walks the given directories and records the package, file
// and scan rank of every top level constant declaration. Only *.go files
// directly inside each directory are read, which matches what swag parses
// per package. The rank increases with each file in scan order, so files
// later in the scan order rank higher.
func scanSources(dirs []string) (*sourceMap, error) {
	m := &sourceMap{}
	rank := 0
	for _, dir := range dirs {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return nil, xerrors.Errorf("scan %s: %w", dir, err)
		}
		for _, entry := range entries {
			if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
				continue
			}
			path := filepath.Join(dir, entry.Name())
			// Test files never contribute constants swag would pick up.
			if strings.HasSuffix(entry.Name(), "_test.go") {
				continue
			}
			pkg, names, err := constNames(path)
			if err != nil {
				return nil, err
			}
			for _, name := range names {
				key := pkg + "." + name
				if _, seen := (*m)[key]; !seen {
					(*m)[key] = sourceInfo{file: entry.Name(), rank: rank}
				}
			}
			rank++
		}
	}
	return m, nil
}

// constNames parses one Go file and returns its package name plus the
// names of its top level constant declarations.
func constNames(path string) (string, []string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return "", nil, xerrors.Errorf("parse %s: %w", path, err)
	}
	var names []string
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for _, ident := range vs.Names {
				names = append(names, ident.Name)
			}
		}
	}
	return f.Name.Name, names, nil
}

// planDefinitionEdits returns one edit per enum array that must be
// reordered. defObjStart and defObjEnd delimit the definitions object.
func planDefinitionEdits(body []byte, defObjStart, defObjEnd int, sources *sourceMap) ([]arrayEdit, error) {
	var edits []arrayEdit
	idx := defObjStart + 1
	for {
		member := nextObjectMember(body, idx, defObjEnd)
		if !member.ok {
			break
		}
		idx = member.next
		if body[member.keyStart] != '"' || body[member.keyEnd-1] != '"' {
			continue
		}
		key := string(body[member.keyStart+1 : member.keyEnd-1])
		if body[member.valStart] != '{' {
			continue
		}
		schemaEdits, err := planSchemaEdits(body, key, member.valStart, member.valEnd, sources)
		if err != nil {
			return nil, err
		}
		edits = append(edits, schemaEdits...)
	}
	return edits, nil
}

// planSchemaEdits returns the edits for one enum schema. defName is the
// definitions key, which is the package-qualified Go type name, for
// example codersdk.Experiment. The package prefix resolves each varname to
// its declaring file.
func planSchemaEdits(body []byte, defName string, schemaStart, schemaEnd int, sources *sourceMap) ([]arrayEdit, error) {
	vnValStart := findMemberValue(body, schemaStart+1, schemaEnd, varnamesKey)
	if vnValStart < 0 {
		return nil, nil
	}
	vnArrStart, vnArrEnd, ok := arrayBounds(body, vnValStart)
	if !ok {
		return nil, nil
	}
	names, err := decodeStringArray(body[vnArrStart:vnArrEnd])
	if err != nil {
		return nil, xerrors.Errorf("%s: %w", defName, err)
	}
	pkg, _, found := strings.Cut(defName, ".")
	if !found {
		return nil, xerrors.Errorf("%s: definition name has no package prefix", defName)
	}
	fork := make([]bool, len(names))
	rank := make([]int, len(names))
	anyFork := false
	for i, name := range names {
		info, ok := (*sources)[pkg+"."+name]
		if ok && IsForkName(info.file) {
			fork[i] = true
			rank[i] = info.rank
			anyFork = true
		}
	}
	if !anyFork {
		return nil, nil
	}
	perm := Plan(names, fork, rank)
	if perm == nil {
		return nil, nil
	}

	var edits []arrayEdit
	for _, member := range enumArrayNames {
		mValStart := findMemberValue(body, schemaStart+1, schemaEnd, member)
		if mValStart < 0 {
			continue
		}
		aStart, aEnd, ok := arrayBounds(body, mValStart)
		if !ok {
			continue
		}
		elems, indent, closeInd, err := splitArray(body, aStart, aEnd)
		if err != nil {
			return nil, xerrors.Errorf("%s.%s: %w", defName, member, err)
		}
		if len(elems) != len(names) {
			return nil, xerrors.Errorf("%s.%s: %d elements, %d varnames", defName, member, len(elems), len(names))
		}
		edits = append(edits, arrayEdit{
			start:    aStart,
			end:      aEnd,
			perm:     perm,
			elems:    elems,
			indent:   indent,
			closeInd: closeInd,
		})
	}
	return edits, nil
}

// arrayEdit replaces one array's bytes with a reordered copy.
type arrayEdit struct {
	start, end int
	perm       []int
	elems      [][]byte
	indent     string
	closeInd   string
}

// spliceEdits applies edits in reverse offset order so earlier offsets stay
// valid.
func spliceEdits(body []byte, edits []arrayEdit) []byte {
	sorted := make([]arrayEdit, len(edits))
	copy(sorted, edits)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].start > sorted[j].start })
	out := body
	for _, e := range sorted {
		reordered, err := ReorderArray(e.elems, e.indent, e.closeInd, e.perm)
		if err != nil {
			// Not reachable: planSchemaEdits validated the arrays.
			panic(fmt.Sprintf("unexpected reorder failure: %s", err))
		}
		next := make([]byte, 0, len(out)-(e.end-e.start)+len(reordered))
		next = append(next, out[:e.start]...)
		next = append(next, reordered...)
		next = append(next, out[e.end:]...)
		out = next
	}
	return out
}

// specBody returns the JSON document inside a swag output file. For
// swagger.json that is the whole file. For docs.go it is the docTemplate
// raw string, which is a sub-slice of the file bytes. The template's
// placeholders all live inside JSON string values except
// {{ marshal .Schemes }}, whose braces the container walk counts without
// needing the value to be valid JSON.
func specBody(data []byte) ([]byte, error) {
	trimmed := bytes.TrimSpace(data)
	if len(trimmed) > 0 && trimmed[0] == '{' {
		return data, nil
	}
	return docTemplateBody(data)
}

// docTemplateOpen marks the start of the spec inside docs.go: the line
// `const docTemplate = `{` opens the raw string with a JSON object.
const docTemplateOpen = "const docTemplate = `{"

// docTemplateClose marks the end of the spec inside docs.go: the raw
// string closes on its own line with a backtick, right after the closing
// brace of the JSON object.
const docTemplateClose = "}`"

// docTemplateBody extracts the JSON spec embedded in docs.go without
// rewriting any bytes, so offsets inside the body are offsets inside the
// file.
func docTemplateBody(data []byte) ([]byte, error) {
	specStart, specEnd, err := docTemplateBounds(data)
	if err != nil {
		return nil, err
	}
	return data[specStart:specEnd], nil
}

// docTemplateBounds returns the byte range of the JSON object embedded in
// docs.go, from the opening `{` to and including the closing `}` that
// precedes the raw string's backtick on the last template line.
func docTemplateBounds(data []byte) (specStart, specEnd int, err error) {
	start := bytes.Index(data, []byte(docTemplateOpen))
	if start < 0 {
		return 0, 0, xerrors.New("docs.go: docTemplate start not found")
	}
	specStart = start + len(docTemplateOpen) - 1 // position of `{`
	relEnd := bytes.Index(data[specStart:], []byte("\n"+docTemplateClose+"\n"))
	if relEnd < 0 {
		return 0, 0, xerrors.New("docs.go: docTemplate end not found")
	}
	return specStart, specStart + relEnd + 2, nil
}

// objectMember holds the byte ranges of one JSON object member: the key
// (with quotes), the value, and the offset of the next member or the
// closing brace.
type objectMember struct {
	keyStart int
	keyEnd   int
	valStart int
	valEnd   int
	next     int
	ok       bool
}

// findObjectMember finds the member with the given key inside the object
// that spans [from, objEnd). ok is false when the key is absent.
func findObjectMember(body []byte, from, objEnd int, key string) objectMember {
	idx := from
	for {
		member := nextObjectMember(body, idx, objEnd)
		if !member.ok {
			return objectMember{}
		}
		if body[member.keyStart] == '"' && body[member.keyEnd-1] == '"' &&
			string(body[member.keyStart+1:member.keyEnd-1]) == key {
			member.ok = true
			return member
		}
		idx = member.next
	}
}

// nextObjectMember parses one object member starting at or after idx: it
// returns the key (with quotes), the value span, and the offset of the
// next member or the object end.
func nextObjectMember(body []byte, idx, objEnd int) objectMember {
	i := skipSpace(body, idx, objEnd)
	if i >= objEnd || body[i] != '"' {
		return objectMember{}
	}
	keyStart := i
	keyEnd, err := skipString(body, i)
	if err != nil {
		return objectMember{}
	}
	i = skipSpace(body, keyEnd, objEnd)
	if i >= objEnd || body[i] != ':' {
		return objectMember{}
	}
	i = skipSpace(body, i+1, objEnd)
	if i >= objEnd {
		return objectMember{}
	}
	valStart := i
	valEnd, _, skipErr := skipValue(body, i, objEnd)
	if skipErr != nil {
		return objectMember{}
	}
	j := skipSpace(body, valEnd, objEnd)
	if j < objEnd && body[j] == ',' {
		j++
	}
	return objectMember{keyStart: keyStart, keyEnd: keyEnd, valStart: valStart, valEnd: valEnd, next: j, ok: true}
}

// findMemberValue returns the value start offset of key inside the object
// that spans [objStart, objEnd), or -1 when the key is absent.
func findMemberValue(body []byte, objStart, objEnd int, key string) int {
	member := findObjectMember(body, objStart, objEnd, key)
	if !member.ok {
		return -1
	}
	return member.valStart
}

// objectBounds returns the open and close offsets of the object value that
// starts at start (body[start] must be '{').
func objectBounds(body []byte, start int) (objStart, objEnd int, err error) {
	return containerBounds(body, start, '{', '}')
}

// arrayBounds returns the open and close offsets of the array value that
// starts at start (body[start] must be '['). ok is false when the value is
// not an array.
func arrayBounds(body []byte, start int) (arrStart, arrEnd int, ok bool) {
	if start >= len(body) || body[start] != '[' {
		return 0, 0, false
	}
	_, end, err := containerBounds(body, start, '[', ']')
	if err != nil {
		return 0, 0, false
	}
	return start, end, true
}

// containerBounds returns the offset just past the closing bracket of the
// container that opens at start. The bracket kinds are not cross checked:
// docs.go embeds Go template placeholders whose braces the depth walk
// counts, which is enough to find the real end of each container.
func containerBounds(body []byte, start int, openCh, _ byte) (openOff, closeOff int, err error) {
	if start >= len(body) || body[start] != openCh {
		return 0, 0, xerrors.New("containerBounds: wrong opening byte")
	}
	i := start + 1
	depth := 1
	for i < len(body) {
		switch body[i] {
		case '"':
			end, err := skipString(body, i)
			if err != nil {
				return 0, 0, err
			}
			i = end
			continue
		case '{', '[':
			depth++
		case '}', ']':
			depth--
			if depth == 0 {
				return start, i + 1, nil
			}
		}
		i++
	}
	return 0, 0, xerrors.New("containerBounds: unterminated container")
}

// escapeSpelling is how swag renders a literal backtick inside the docs.go
// raw string: it closes the string, quotes the backtick as Go source and
// reopens the raw string. It is 11 bytes and can only appear inside a JSON
// string value, so the scanner treats it as one opaque token and never
// mistakes its quotes for JSON string boundaries.
const escapeSpelling = "` + \"`\" + `"

// skipString returns the offset just past a JSON string that opens at
// body[start] == '"'. In docs.go, backtick escape spellings inside the
// string are skipped whole: a backtick there is always the first byte of
// the escape because swag rewrites every literal backtick in the raw
// string. In swagger.json a backtick is ordinary string content.
func skipString(body []byte, start int) (int, error) {
	escapes := isDocTemplateBody(body)
	i := start + 1
	for i < len(body) {
		switch body[i] {
		case '\\':
			i += 2
			continue
		case '"':
			return i + 1, nil
		case '`':
			if escapes {
				if bytes.HasPrefix(body[i:], []byte(escapeSpelling)) {
					i += len(escapeSpelling)
					continue
				}
				return 0, xerrors.New("unexpected bare backtick in docs.go JSON string")
			}
		}
		i++
	}
	return 0, xerrors.New("unterminated string")
}

// isDocTemplateBody reports whether the body is the docs.go template, by
// looking for its escape placeholder near the top.
func isDocTemplateBody(body []byte) bool {
	end := len(body)
	if end > 4096 {
		end = 4096
	}
	return bytes.Contains(body[:end], []byte("{{escape .Description}}"))
}

// skipValue returns the end offset of the JSON value that starts at start,
// plus the offset of the first byte after any trailing whitespace.
func skipValue(body []byte, start, limit int) (end, after int, err error) {
	switch body[start] {
	case '"':
		end, err := skipString(body, start)
		if err != nil {
			return 0, 0, err
		}
		return end, skipSpace(body, end, limit), nil
	case '{', '[':
		_, end, err := containerBounds(body, start, body[start], closingOf(body[start]))
		if err != nil {
			return 0, 0, err
		}
		return end, skipSpace(body, end, limit), nil
	default:
		i := start
		for i < limit {
			switch body[i] {
			case ',', '}', ']', ' ', '\t', '\n', '\r':
				return i, skipSpace(body, i, limit), nil
			}
			i++
		}
		return i, i, nil
	}
}

func closingOf(open byte) byte {
	if open == '{' {
		return '}'
	}
	return ']'
}

// skipSpace returns the offset of the first non whitespace byte at or
// after idx, bounded by limit.
func skipSpace(body []byte, idx, limit int) int {
	for idx < limit {
		switch body[idx] {
		case ' ', '\t', '\n', '\r':
			idx++
		default:
			return idx
		}
	}
	return idx
}

// splitArray splits a pretty printed JSON array into element byte slices
// plus the indentation swag used. MarshalIndent output puts every element
// on its own line at one indent level, ends each line with a comma except
// the last, and closes the array at one level less indentation.
func splitArray(body []byte, start, end int) (elems [][]byte, indent, closeInd string, err error) {
	if end-start < 2 {
		return nil, "", "", xerrors.New("array too short")
	}
	inner := body[start+1 : end-1]
	if len(bytes.TrimSpace(inner)) == 0 {
		// Empty array: nothing to reorder, no elements.
		return nil, "", "", nil
	}
	lines := bytes.Split(inner, []byte("\n"))
	if len(lines) < 3 {
		return nil, "", "", xerrors.New("array is not multiline")
	}
	if len(bytes.TrimSpace(lines[0])) != 0 {
		return nil, "", "", xerrors.New("first element shares a line with the bracket")
	}
	closeInd = string(lines[len(lines)-1])
	if len(strings.TrimSpace(closeInd)) != 0 {
		return nil, "", "", xerrors.New("closing bracket shares a line with an element")
	}
	for _, line := range lines[1 : len(lines)-1] {
		trimmed := bytes.TrimSpace(line)
		if len(trimmed) == 0 {
			return nil, "", "", xerrors.New("blank line inside array")
		}
		elems = append(elems, trimmed)
	}
	// Strip the trailing comma from the last element; ReorderArray re
	// adds separators.
	last := elems[len(elems)-1]
	elems[len(elems)-1] = bytes.TrimSuffix(last, []byte(","))
	// The indentation is the whitespace prefix of any element line.
	firstLine := lines[1]
	indent = string(firstLine[:len(firstLine)-len(bytes.TrimSpace(firstLine))])
	return elems, indent, closeInd, nil
}

// decodeStringArray decodes a JSON array of strings from its exact bytes.
func decodeStringArray(raw []byte) ([]string, error) {
	var out []string
	dec := json.NewDecoder(bytes.NewReader(raw))
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	if d, ok := tok.(json.Delim); !ok || d != '[' {
		return nil, xerrors.New("not a JSON array")
	}
	for {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		if d, ok := tok.(json.Delim); ok {
			if d == ']' {
				return out, nil
			}
			return nil, xerrors.New("unexpected delimiter in string array")
		}
		s, ok := tok.(string)
		if !ok {
			return nil, xerrors.New("non string element in string array")
		}
		out = append(out, s)
	}
}
